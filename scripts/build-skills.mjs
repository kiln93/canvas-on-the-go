// Bundles the design skill files in server/skills into one TypeScript module, so the serverless
// functions get them without reading files at runtime. Run after changing anything in server/skills.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const ORDER = [
  "impeccable/ios.md",
  "impeccable/adapt.native.md",
  "impeccable/mode-operate.md",
  "impeccable/craft-floor.md",
  "open-design/mobile-layouts.md",
  "open-design/mobile-checklist.md",
  "open-design/state-coverage.md",
  "open-design/anti-ai-slop.md",
  "open-design/animation-discipline.md",
  "hallmark/flow.md",
  "frontend-design/SKILL.md",
];
const all = readdirSync("server/skills", { recursive: true }).filter((f) => String(f).endsWith(".md") && f !== "NOTICE.md");
const missing = all.filter((f) => !ORDER.includes(String(f)));
if (missing.length) throw new Error(`Add these to ORDER in scripts/build-skills.mjs: ${missing.join(", ")}`);

const body = ORDER.map((f) => `<skill file="${f}">\n${readFileSync(`server/skills/${f}`, "utf8").trim()}\n</skill>`).join("\n\n");
writeFileSync(
  "server/skills.ts",
  `// Generated by scripts/build-skills.mjs from server/skills (see server/skills/NOTICE.md for sources and licenses). Do not edit.\nexport const SKILLS = ${JSON.stringify(body)};\n`,
);
console.log(`Bundled ${ORDER.length} skill files (${body.length} chars) into server/skills.ts`);
